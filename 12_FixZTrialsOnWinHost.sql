--============================================================
--Step 1: move entries off Z trials to their non-Z twin, excluding natural-key
--collisions (those ~44 stay put for the admin).
--============================================================

UPDATE ze
SET ze.TrialId = nz.TrialId
FROM MSSA_Entries ze
JOIN MSSA_Trials z ON z.TrialId = ze.TrialId
JOIN MSSA_Trials nz ON nz.TrialIdentifier = LEFT(z.TrialIdentifier, LEN(z.TrialIdentifier)-1) AND nz.EventId = z.EventId
WHERE z.TrialIdentifier LIKE '%Z'
  AND NOT EXISTS (
      SELECT 1 FROM MSSA_Entries nze
      WHERE nze.TrialId = nz.TrialId AND nze.DogId = ze.DogId AND nze.HandlerId = ze.HandlerId AND nze.ClassId = ze.ClassId
  );

--============================================================
--Step 2: insert the legitimate new trials under fresh local IDs.
--============================================================

INSERT INTO MSSA_Trials (EventId, TrialIdentifier, TrialDate, TrialName, Stock)
SELECT ev.EventId, nt.TrialIdentifier, nt.TrialDate, NULL, nt.Stock
FROM #NewTrials nt
JOIN MSSA_Events ev ON ev.EventIdentifier = nt.EventIdentifier
WHERE NOT EXISTS (
    SELECT 1 FROM MSSA_Trials existing WHERE existing.EventId = ev.EventId AND existing.TrialIdentifier = nt.TrialIdentifier
);

--============================================================
--Step 3: fix entries that were already present (from an earlier merge run) under
--the stale Trial_ID, onto their correct new trial.
--============================================================

UPDATE e
SET e.TrialId = t.TrialId
FROM MSSA_Entries e
JOIN #EntryFix ef ON ef.EntryId = e.EntryId
JOIN MSSA_Trials t ON t.TrialIdentifier = ef.CorrectTrialIdentifier
WHERE e.TrialId <> t.TrialId;

--============================================================
--Step 4: recompute EventClassOfferings (targeted update + insert, not a full wipe).
--============================================================

;WITH Recomputed AS (
    SELECT t.EventId, e.ClassId, ISNULL(t.Stock, 'Cattle') as Stock, COUNT(*) as PlannedRuns
    FROM MSSA_Entries e JOIN MSSA_Trials t ON e.TrialId = t.TrialId
    GROUP BY t.EventId, e.ClassId, t.Stock
)
UPDATE o SET o.PlannedRuns = r.PlannedRuns
FROM MSSA_EventClassOfferings o JOIN Recomputed r ON r.EventId = o.EventId AND r.ClassId = o.ClassId
WHERE o.PlannedRuns <> r.PlannedRuns;

INSERT INTO MSSA_EventClassOfferings (EventId, ClassId, Stock, Venue, PlannedRuns)
SELECT t.EventId, e.ClassId, ISNULL(t.Stock, 'Cattle'), 'Arena', COUNT(*)
FROM MSSA_Entries e JOIN MSSA_Trials t ON e.TrialId = t.TrialId
WHERE NOT EXISTS (SELECT 1 FROM MSSA_EventClassOfferings o WHERE o.EventId = t.EventId AND o.ClassId = e.ClassId)
GROUP BY t.EventId, e.ClassId, t.Stock;

